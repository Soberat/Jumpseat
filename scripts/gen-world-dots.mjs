// Regenerates src/lib/world-dots.ts: a dot-matrix land mask for the route map.
// Run with `node scripts/gen-world-dots.mjs` (needs the world-atlas dev dependency).
import { readFileSync, writeFileSync } from 'node:fs';
import { geoContains } from 'd3-geo';
import { feature } from 'topojson-client';

const STEP = 1.5;
const NORTH = 76.5;
const SOUTH = -55.5;
const topo = JSON.parse(readFileSync('node_modules/world-atlas/land-50m.json', 'utf8'));
const land = feature(topo, topo.objects.land);

const rows = [];
for (let lat = NORTH; lat >= SOUTH; lat -= STEP) {
	let bits = '';
	for (let lon = -180; lon < 180; lon += STEP) {
		bits += geoContains(land, [lon + STEP / 2, lat]) ? '1' : '0';
	}
	// 4 cells per hex digit.
	rows.push(
		bits
			.match(/.{4}/g)
			.map((b) => parseInt(b, 2).toString(16))
			.join('')
	);
}

writeFileSync(
	'src/lib/world-dots.ts',
	`// Generated by scripts/gen-world-dots.mjs from Natural Earth (world-atlas, 1:50m). Do not edit.
export const DOT_STEP = ${STEP};
export const DOT_NORTH = ${NORTH};
/** One row per latitude band from north to south; each hex digit is 4 cells of ${STEP}° from 180°W. */
export const LAND_ROWS = ${JSON.stringify(rows, null, '\t')};
`
);
console.log(
	rows.length,
	'rows,',
	rows
		.join('')
		.split('')
		.reduce((n, h) => n + parseInt(h, 16).toString(2).replace(/0/g, '').length, 0),
	'land dots'
);
